-- Familia Food — Expansion skema untuk modul Supplier/Pembelian/Pelanggan/Retur.
-- Jalankan SUPABASE-OWNER-AUTH.sql setelah seluruh tabel inti dan modul tersedia.
-- Jangan aktifkan kebijakan akses terbuka untuk anon.

create table if not exists public.pengeluaran_kategori_master (
  id bigint generated by default as identity primary key,
  nama_kategori text not null unique,
  aktif boolean not null default true,
  urutan integer not null default 0,
  created_at timestamptz not null default now()
);
insert into public.pengeluaran_kategori_master (nama_kategori,aktif,urutan)
values ('Bahan Baku',true,1),('Operasional',true,2),('Gaji',true,3),('Alat & Perlengkapan',true,4),('Retur',true,5),('Lainnya',true,6)
on conflict (nama_kategori) do nothing;
alter table public.pengeluaran_kategori_master enable row level security;
drop policy if exists "pengeluaran_kategori_master_anon_all" on public.pengeluaran_kategori_master;

create index if not exists pengeluaran_kategori_master_urutan_idx on public.pengeluaran_kategori_master(urutan,id);

create table if not exists public.ff_supplier (
  id bigint generated by default as identity primary key,
  nama text not null,
  telepon text,
  alamat text,
  catatan text,
  status text not null default 'Aktif',
  created_at timestamptz not null default now()
);

create table if not exists public.ff_pelanggan (
  id bigint generated by default as identity primary key,
  nama text not null,
  telepon text,
  alamat text,
  catatan text,
  status text not null default 'Aktif',
  created_at timestamptz not null default now()
);

create table if not exists public.ff_pembelian (
  id bigint generated by default as identity primary key,
  tanggal date not null,
  supplier_id bigint references public.ff_supplier(id) on delete set null,
  total numeric not null default 0,
  catatan text,
  created_at timestamptz not null default now()
);

create table if not exists public.ff_pembelian_item (
  id bigint generated by default as identity primary key,
  pembelian_id bigint not null references public.ff_pembelian(id) on delete cascade,
  bahan_id bigint references public.bahan_baku(id) on delete set null,
  nama_bahan text not null,
  qty numeric not null default 0,
  satuan text,
  harga_beli numeric not null default 0,
  subtotal numeric not null default 0,
  catatan text
);

create table if not exists public.ff_retur_penjualan (
  id bigint generated by default as identity primary key,
  tanggal date not null,
  penjualan_id bigint references public.penjualan(id) on delete set null,
  channel text not null default 'Offline',
  produk_id bigint references public.produk(id) on delete set null,
  nama_produk text not null,
  qty numeric not null default 0,
  nominal numeric not null default 0,
  alasan text,
  created_at timestamptz not null default now()
);

create table if not exists public.ff_penjualan_pelanggan (
  id bigint generated by default as identity primary key,
  penjualan_id bigint not null unique references public.penjualan(id) on delete cascade,
  pelanggan_id bigint not null references public.ff_pelanggan(id) on delete restrict,
  created_at timestamptz not null default now()
);

create index if not exists ff_pelanggan_map_pelanggan_idx on public.ff_penjualan_pelanggan(pelanggan_id);
create index if not exists ff_pembelian_tanggal_idx on public.ff_pembelian(tanggal);
create index if not exists ff_pembelian_item_pembelian_idx on public.ff_pembelian_item(pembelian_id);
create index if not exists ff_retur_tanggal_idx on public.ff_retur_penjualan(tanggal);

-- Keep module tables closed until the owner-only RLS migration is applied.
alter table public.ff_supplier enable row level security;
alter table public.ff_pelanggan enable row level security;
alter table public.ff_pembelian enable row level security;
alter table public.ff_pembelian_item enable row level security;
alter table public.ff_retur_penjualan enable row level security;
alter table public.ff_penjualan_pelanggan enable row level security;
alter table public.pengeluaran_kategori_master enable row level security;

revoke all privileges on table
  public.ff_supplier, public.ff_pelanggan, public.ff_pembelian,
  public.ff_pembelian_item, public.ff_retur_penjualan,
  public.ff_penjualan_pelanggan, public.pengeluaran_kategori_master
from anon;

-- Give Data API CRUD to authenticated users and service_role only.
-- RLS remains the row-level boundary; owner policies are installed by
-- SUPABASE-OWNER-AUTH.sql.
grant select, insert, update, delete on table
  public.ff_supplier,
  public.ff_pelanggan,
  public.ff_pembelian,
  public.ff_pembelian_item,
  public.ff_retur_penjualan,
  public.ff_penjualan_pelanggan,
  public.pengeluaran_kategori_master
to authenticated, service_role;

grant usage, select on sequence
  public.ff_supplier_id_seq,
  public.ff_pelanggan_id_seq,
  public.ff_pembelian_id_seq,
  public.ff_pembelian_item_id_seq,
  public.ff_retur_penjualan_id_seq,
  public.ff_penjualan_pelanggan_id_seq,
  public.pengeluaran_kategori_master_id_seq
to authenticated, service_role;

